#!/usr/bin/env bash
# Regenerate `go-aggregate-views.toml` from the read-only Go tree.
#
# WHY THIS FILE EXISTS AT ALL
#
# The old continuous-aggregate views name a bucket's *mean* after the column itself —
# `avg(outtemp) AS outtemp` — and name a bucket's *maximum* after the column itself for a
# different set of metrics — `max(dayrain) AS dayrain`. So "which old column holds which
# statistic" is not derivable from a column name and it is not derivable from
# metrics/registry.toml either. It is only in the view definitions, and the archive
# transform in docs/data-migration.md §4 needs it for all 399 columns.
#
# Extracting it mechanically from the Go source, rather than transcribing it, is the
# difference between a mapping that is right and a mapping that looks right.
#
# Usage: ci/db/migrate-from-go/extract-go-views.sh <path-to-remoteweather-checkout>
set -euo pipefail
RW="${1:?usage: extract-go-views.sh <path-to-remoteweather-checkout>}"
SRC="$RW/internal/storage/timescaledb/sql.go"
[ -f "$SRC" ] || { echo "not a remoteweather checkout: $SRC missing" >&2; exit 2; }
SHA="$(git -C "$RW" rev-parse HEAD)"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/go-aggregate-views.toml"

python3 - "$SRC" "$SHA" > "$OUT" <<'PY'
import re, sys
src, sha = open(sys.argv[1]).read(), sys.argv[2]
consts = dict(re.findall(r'const\s+(\w+)\s*=\s*`(.*?)`', src, re.S))

def parse(name):
    body = re.sub(r'--[^\n]*', '', consts[name])        # strip line comments
    sel = body.split('SELECT', 1)[1].split('\nFROM', 1)[0]
    out = []
    for part in sel.split(','):
        p = ' '.join(part.split()).rstrip(',')
        if not p or re.match(r"^time_bucket\('[^']+'$", p):
            continue
        if p == "time) as bucket":
            out.append(('bucket', 'time_bucket', '', '')); continue
        m = re.match(r'^(\w+)\(([^()]*)\)(::\w+)?\s+as\s+(\w+)$', p, re.I)
        if m:
            out.append((m.group(4), m.group(1).lower(), m.group(2).strip(), m.group(3) or '')); continue
        m = re.match(r'^(\w+)$', p)
        if m:
            out.append((m.group(1), 'group', m.group(1), '')); continue
        raise SystemExit("extract-go-views: unparsed select item: %r" % p)
    return out

views = {n: parse(c) for n, c in [('1m','create1mViewSQL'), ('5m','create5mViewSQL'),
                                  ('1h','create1hViewSQL'), ('1d','create1dViewSQL')]}

# The four views are expected to be shape-identical apart from the bucket width. If that
# ever stops being true, one mapping can no longer serve all four and this must fail.
base = set(views['1d'])
for n, v in views.items():
    if set(v) != base:
        raise SystemExit("extract-go-views: weather_%s differs in shape from weather_1d; "
                         "the single mapping assumption is broken" % n)

print("# GENERATED by ci/db/migrate-from-go/extract-go-views.sh. DO NOT EDIT.")
print("#")
print("# The output column list of the Go implementation's four continuous-aggregate views,")
print("# extracted from internal/storage/timescaledb/sql.go. All four views are")
print("# shape-identical apart from the bucket width, which the extractor asserts, so one")
print("# mapping serves weather_1m, weather_5m, weather_1h and weather_1d.")
print("#")
print("# `func` is the aggregate the old view applied; `arg` is the raw column it applied it")
print("# to; `cast` records that the old view truncated the result (`avg(x)::int`).")
print()
print('source_repo = "github.com/chrissnell/remoteweather"')
print('source_commit = "%s"' % sha)
print('source_file = "internal/storage/timescaledb/sql.go"')
print('views = ["weather_1m", "weather_5m", "weather_1h", "weather_1d"]')
print('column_count = %d' % len(views['1d']))
print()
for name, func, arg, cast in views['1d']:
    print('[[column]]')
    print('name = "%s"' % name)
    print('func = "%s"' % func)
    print('arg = "%s"' % arg)
    if cast:
        print('cast = "%s"' % cast.lstrip(':'))
    print()
PY
echo "wrote $OUT ($(grep -c '^\[\[column\]\]' "$OUT") columns, remoteweather $SHA)"
