fn openapi(reg: &Registry) -> String {
    use serde_json::{json, Map, Value};
    let mut reading = Map::new();
    let mut required = Vec::new();
    for d in &reg.dimensions {
        let (t, f) = d.sql_type.openapi();
        reading.insert(d.key.clone(), prop(t, f, &d.label, None));
        if d.role != Role::Attribute {
            required.push(Value::String(d.key.clone()));
        }
    }
    for m in reg.live_metrics() {
        let (t, f) = m.sql_type.openapi();
        reading.insert(m.key.clone(), prop(t, f, &m.label, Some(&m.unit)));
    }

    // The frozen legacy surface, keyed by its own JSON names. W1 owns this surface;
    // what is generated here is the metric-to-key mapping the registry records, so
    // that nobody hand-writes a mapping layer again. Derived values that are not
    // metrics (rainfall windows, wind gust, cardinal direction, moon phase, the
    // formatted sun times) are W1's and are deliberately absent.
    let mut legacy = Map::new();
    for d in &reg.dimensions {
        for k in &d.legacy_rest_keys {
            let (t, f) = d.sql_type.openapi();
            legacy.insert(k.clone(), prop(t, f, &d.label, None));
        }
    }
    for m in reg.live_metrics() {
        for k in &m.legacy_rest_keys {
            let (t, f) = m.sql_type.openapi();
            let mut p = prop(t, f, &m.label, Some(&m.unit));
            p["x-metric"] = json!(m.key);
            if m.legacy_read_time_computed {
                p["x-legacy-read-time-computed"] = json!(true);
            }
            legacy.insert(k.clone(), p);
        }
        for (agg, keys) in &m.legacy_aggregate_rest_keys {
            for k in keys {
                let mut p = prop("number", Some("double"), &m.label, Some(&m.unit));
                p["x-metric"] = json!(m.key);
                p["x-aggregate"] = json!(agg);
                legacy.insert(k.clone(), p);
            }
        }
    }

    let doc = json!({
        "openapi": "3.1.0",
        "info": {
            "title": "ModernWeather reading schemas",
            "version": "0.1.0",
            "description":
                "Generated from metrics/registry.toml by `cargo xtask codegen`. Do not edit. \
                 Paths are not described here: this document carries the reading schemas only, \
                 and the endpoint surface is W1's (frozen legacy contract) and W3's (new \
                 endpoints)."
        },
        "x-generated-by": "cargo xtask codegen",
        "x-source": "metrics/registry.toml",
        "paths": {},
        "components": {
            "schemas": {
                "Reading": {
                    "type": "object",
                    "description": "One reading, keyed by registry stable key.",
                    "required": required,
                    "properties": Value::Object(reading)
                },
                "LegacyWeatherReading": {
                    "type": "object",
                    "description":
                        "The frozen legacy REST reading, keyed by its shipped JSON names. \
                         The names are inconsistent and two measurements are served under \
                         two keys each ('outhumidity'/'ohum' and 'dayrain'/'rainday'); that \
                         is recorded, not fixed (D-37). Derived values that are not metrics \
                         are W1's and are not generated here.",
                    "properties": Value::Object(legacy)
                }
            }
        }
    });
    let mut s = serde_json::to_string_pretty(&doc).expect("serialisable");
    s.push('\n');
    s
}

fn prop(t: &str, f: Option<&str>, label: &str, unit: Option<&str>) -> serde_json::Value {
    use serde_json::json;
    let mut v = json!({ "type": [t, "null"], "description": label });
    if let Some(f) = f {
        v["format"] = json!(f);
    }
    if let Some(u) = unit {
        if u != "unitless" {
            v["x-unit"] = json!(u);
        }
    }
    v
}

