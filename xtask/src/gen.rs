fn aggregate_sql(reg: &Registry, level: &str) -> String {
    let lvl = reg.level(level).expect("validated level");
    let cols = reg.level_columns(level);
    let t = &reg.time_column().column;
    let p = &reg.partition_column().column;
    let from_raw = lvl.source == "raw";
    let (source_table, bucket_src) = if from_raw {
        (RAW_TABLE.to_string(), t.clone())
    } else {
        (format!("{RAW_TABLE}_{}", lvl.source), "bucket".to_string())
    };

    let mut s = header("--");
    let _ = write!(
        s,
        "-- {RAW_TABLE}_{level}: {} buckets, read from {}.\n\
         --\n\
         -- Three properties of this file are not negotiable, are easy to get wrong, and are\n\
         -- silent when wrong. They are properties of the generator's template, not of\n\
         -- whoever called it:\n\
         --\n\
         --   * sums accumulate in double precision, never in the column's own type. \
         `sum(real)`\n\
         --     returns `real`, float4 addition is not associative, and a hierarchy therefore\n\
         --     adds in a different order than a direct scan — measured wrong in 55 of 56\n\
         --     uneven-bucket pairs, bit-identical in 56 of 56 once widened (D-14).\n\
         --   * counts are nulled at zero. `count()` returns 0 and never NULL, so on a\n\
         --     70%-NULL table a plain count column is fully populated and almost entirely\n\
         --     zeroes — 347 MB against 234 MB on a 398-column month (D-16).\n\
         --   * no column holds a finished average. {}\n\
         --     `avg(avg(x))` was wrong in 658 of 868 real pairs and in all 56 uneven ones\n\
         --     (D-11, D-12). Means are finalised at query time by mw_mean().\n\
         --\n\
         -- Refresh policy, compression and retention for this view are W4's (OQ-4) and are\n\
         -- deliberately not generated here.\n\n",
        lvl.bucket,
        if from_raw {
            "the raw hypertable".to_string()
        } else {
            source_table.clone()
        },
        if from_raw {
            "This is the only level that reads raw."
        } else {
            "This level reads the level below it, never raw."
        }
    );

    let _ = writeln!(
        s,
        "CREATE MATERIALIZED VIEW {RAW_TABLE}_{level}\n\
         WITH (timescaledb.continuous, timescaledb.materialized_only = {}) AS\n\
         SELECT\n\
         \x20   time_bucket(INTERVAL '{}', {bucket_src}) AS bucket,\n\
         \x20   {p},",
        lvl.materialized_only, lvl.bucket
    );

    let mut body: Vec<String> = Vec::new();
    let mut last_metric = "";
    for (m, c) in &cols {
        if m.key != last_metric {
            last_metric = &m.key;
            body.push(format!("    -- {} [{}]", m.label, m.key));
        }
        let expr = if from_raw { &c.from_raw } else { &c.from_level };
        body.push(format!("    {expr} AS {}", c.name));
    }
    s.push_str(&body.join(",\n").replacen(",\n    --", "\n    --", 0));
    // The comment lines must not carry a trailing comma; re-join carefully.
    s = fixup_comment_commas(s);
    let _ = write!(
        s,
        "\nFROM {source_table}\nGROUP BY 1, 2\nWITH NO DATA;\n\n\
         -- {} aggregate expressions over {} metrics. Ceiling is 1598 \
         (1598 + bucket + {p} = 1600).\n",
        cols.len(),
        reg.metrics
            .iter()
            .filter(|m| m.in_level(&reg.defaults, level))
            .count()
    );
    s
}

/// `body.join(",\n")` puts a comma after the comment lines too. Strip those.
fn fixup_comment_commas(s: String) -> String {
    s.lines()
        .map(|l| {
            let t = l.trim_start();
            if t.starts_with("--") && l.ends_with(',') {
                l[..l.len() - 1].to_string()
            } else {
                l.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// The shape W4's rebuild procedure executes. Not a migration: refreshing a
/// continuous aggregate cannot run inside a transaction, and D-17 requires the
/// session to relax commit durability — a full refresh is fsync-bound and measured
/// 306 s against 25.6 s.
fn rebuild_sql(reg: &Registry) -> String {
    let mut s = header("--");
    s.push_str(
        "-- Aggregate rebuild. Run with psql, NOT as a migration: refresh_continuous_aggregate\n\
         -- cannot run inside a transaction, and sqlx wraps a migration in one.\n\
         --\n\
         -- Aggregates are disposable derived data (D-15). The supported way to change one is\n\
         -- to drop it, regenerate it and refresh it; there is no in-place aggregate\n\
         -- migration and no versioning scheme.\n\
         --\n\
         -- The relaxed durability below is required, not an optimisation: a full refresh of\n\
         -- the minute level over 36 M raw rows took 306 s with synchronous_commit on and\n\
         -- 25.6 s with it off, and the identical aggregation as a plain query takes 2.4 s.\n\
         -- The cost is WAL fsync, not CPU, and it is safe here for exactly the reason the\n\
         -- aggregates are disposable: a crash mid-rebuild costs a re-run, not information.\n\
         -- Ingest keeps full durability; this is a property of this session only.\n\n\
         SET synchronous_commit = off;\n\n",
    );
    for lvl in &reg.levels {
        let _ = writeln!(
            s,
            "CALL refresh_continuous_aggregate('{RAW_TABLE}_{}', NULL, NULL);",
            lvl.name
        );
    }
    s.push_str(
        "\n-- Order matters: each level reads the level below it, so refreshing top-down\n\
         -- would materialise an upper level from a stale lower one.\n",
    );
    s
}

