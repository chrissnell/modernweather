/// The two finalisers. Neither aggregate level stores a finished average or a
/// finished angle (D-12, H-3), so reading one back is a function call at query time.
fn functions_sql() -> String {
    let mut s = header("--");
    s.push_str(
        "-- Finalisers for the composable state the aggregates store. They are the only\n\
         -- place a mean or an angle is computed, which is what keeps `avg(avg(x))` from\n\
         -- being expressible: no level stores a finished average to average.\n\n\
         CREATE OR REPLACE FUNCTION mw_mean(total double precision, n bigint)\n\
         RETURNS double precision\n\
         LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$\n\
         \x20   SELECT CASE WHEN n IS NULL OR n = 0 THEN NULL ELSE total / n END\n\
         $$;\n\n\
         -- Vector mean of an angle, finalised from the sine sum, cosine sum and count the\n\
         -- aggregates carry. Verified through the level hierarchy against a direct\n\
         -- computation from raw: agreement to within 3e-12 degrees over 868 bucket pairs\n\
         -- (D-13).\n\
         --\n\
         -- The empty-bucket branch returns 0, not NULL, and that is a contract requirement\n\
         -- rather than a convenience (OQ-W1-2 option (c), W3 assumption 18). W1-BUG-1:\n\
         -- the Go finaliser divides sin_sum by a zero count and /span is a 500 with\n\
         -- SQLSTATE 22012 for any station reporting no winddir. It is latent there only\n\
         -- because the Go writer inserts its whole struct, zeros included, so windd\n\
         -- serialises as 0. This design's writer stores NULL for an unreported metric\n\
         -- (W3 §2.5), which makes the defect live. Returning NULL instead would be a\n\
         -- contract change: `windd` is a non-optional Swift Double, and a missing key\n\
         -- fails the decode of the entire /span response, not just that field. 0 is what\n\
         -- ships today and 0 is what this returns.\n\
         CREATE OR REPLACE FUNCTION mw_circular_mean(\n\
         \x20   sin_sum double precision,\n\
         \x20   cos_sum double precision,\n\
         \x20   n       bigint\n\
         ) RETURNS double precision\n\
         LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$\n\
         \x20   SELECT CASE\n\
         \x20       WHEN n IS NULL OR n = 0 OR sin_sum IS NULL OR cos_sum IS NULL THEN 0\n\
         \x20       ELSE (atan2d(sin_sum / n, cos_sum / n) + 360)::numeric % 360\n\
         \x20   END::double precision\n\
         $$;\n",
    );
    s
}

// ---------------------------------------------------------------------------
// SQL: the raw hypertable
// ---------------------------------------------------------------------------

fn table_sql(reg: &Registry) -> String {
    let mut s = header("--");
    let _ = writeln!(
        s,
        "-- The raw hypertable. One column per metric (D-3): PostgreSQL stores a NULL as one\n\
         -- bit in the row's null bitmap, so a declared-but-empty column costs a bit and not a\n\
         -- value. Every metric column is nullable, which is also what makes adding one cheap\n\
         -- (D-9: 11.6 ms against ~1 GB of compressed chunks).\n"
    );
    let _ = writeln!(s, "CREATE TABLE {RAW_TABLE} (");
    let mut lines: Vec<String> = Vec::new();
    let width = reg
        .dimensions
        .iter()
        .map(|d| d.column.len())
        .chain(reg.metrics.iter().map(|m| m.column.len()))
        .max()
        .unwrap_or(10);
    for d in &reg.dimensions {
        let null = if d.role == Role::Attribute {
            "NULL"
        } else {
            "NOT NULL"
        };
        lines.push(format!(
            "    {:<width$} {:<12} {null}",
            d.column,
            d.sql_type.ddl(),
            width = width
        ));
    }
    for m in reg.metrics_ordered() {
        let dep = if m.deprecated {
            "  -- deprecated, identifiers retained".to_string()
        } else if let Some(n) = &m.note {
            format!("  -- {n}")
        } else {
            String::new()
        };
        lines.push(format!(
            "    {:<width$} {:<12} NULL{dep}",
            m.column,
            m.sql_type.ddl(),
            width = width
        ));
    }
    s.push_str(&lines.join(",\n"));
    s.push_str("\n);\n\n");

    let t = &reg.time_column().column;
    let p = &reg.partition_column().column;
    let _ = write!(
        s,
        "SELECT create_hypertable('{RAW_TABLE}', '{t}', chunk_time_interval => INTERVAL '7 days');\n\n\
         -- Compression is configured at creation, not retrofitted (D-7). Segmenting by the\n\
         -- partition column and ordering by descending time is what the measured 11.2x ratio\n\
         -- was measured with.\n\
         ALTER TABLE {RAW_TABLE} SET (\n\
         \x20   timescaledb.compress,\n\
         \x20   timescaledb.compress_segmentby = '{p}',\n\
         \x20   timescaledb.compress_orderby   = '{t} DESC'\n\
         );\n\
         SELECT add_compression_policy('{RAW_TABLE}', INTERVAL '7 days');\n\n\
         -- No retention policy, deliberately (D-4). Raw readings are retained indefinitely;\n\
         -- that is what makes the aggregates disposable derived data and adding a metric\n\
         -- cheap. Production's 365-day policy is the direct cause of the ~294 days that now\n\
         -- exist only as rollups.\n\n\
         -- Indexes beyond the hypertable's own time index are W4's (query shapes, not\n\
         -- metric definitions), so none is generated here.\n"
    );
    s
}

