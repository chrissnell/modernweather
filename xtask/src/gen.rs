fn proto(reg: &Registry) -> String {
    let mut s = header("//");
    s.push_str(
        "// Field numbers come from the registry and are never renumbered. A reused number\n\
         // silently reinterprets historical data on every client that has not been rebuilt,\n\
         // which is how the Go implementation ended up wedging station metadata into 188-192\n\
         // and relays 8-10 into 193-195 (D-21).\n\n\
         syntax = \"proto3\";\n\n\
         package modernweather.v1;\n\n\
         import \"google/protobuf/timestamp.proto\";\n\n\
         message Reading {\n",
    );
    let mut reserved: Vec<u32> = Vec::new();
    for d in &reg.dimensions {
        let _ = writeln!(
            s,
            "    {} {} = {};  // {}",
            d.proto_type, d.proto_name, d.field_number, d.label
        );
    }
    s.push('\n');
    for m in reg.metrics_ordered() {
        if m.deprecated {
            reserved.push(m.field_number);
            continue;
        }
        let unit = if m.unit == "unitless" {
            String::new()
        } else {
            format!(" ({})", m.unit)
        };
        let _ = writeln!(
            s,
            "    {} {} = {};  // {}{unit}",
            m.proto_type, m.proto_name, m.field_number, m.label
        );
    }
    if !reserved.is_empty() {
        s.push_str("\n    // Deprecated metrics. The numbers stay reserved forever (D-21).\n");
        let list: Vec<String> = reserved.iter().map(|n| n.to_string()).collect();
        let _ = writeln!(s, "    reserved {};", list.join(", "));
    }
    s.push_str("}\n");
    s
}

