fn ts_reading(reg: &Registry) -> String {
    let mut s = header("//");
    s.push_str("export interface Reading {\n");
    for d in &reg.dimensions {
        let opt = if d.role == Role::Attribute {
            " | null"
        } else {
            ""
        };
        let _ = writeln!(s, "  /** {} (`{}`) */", d.label, d.column);
        let _ = writeln!(s, "  {}: {}{opt};", d.key, d.sql_type.ts());
    }
    s.push('\n');
    for m in reg.live_metrics() {
        let _ = writeln!(s, "  /** {} — {} (`{}`) */", m.label, m.unit, m.column);
        let _ = writeln!(s, "  {}: {} | null;", m.key, m.sql_type.ts());
    }
    s.push_str("}\n");
    s
}

/// The label/unit table the management UI renders from.
fn ts_metrics(reg: &Registry) -> String {
    let mut s = header("//");
    s.push_str(
        "// The table the management UI renders metric names and units from. Labels are\n\
         // user-facing: W5 §0 owns the vocabulary translation table and is authoritative\n\
         // where it and this file disagree (D-36).\n\n\
         export type Tier = 'core' | 'extended';\n\n\
         export interface MetricMeta {\n\
         \x20 /** Registry stable key. Also the property name on Reading. */\n\
         \x20 key: string;\n\
         \x20 column: string;\n\
         \x20 label: string;\n\
         \x20 unit: string;\n\
         \x20 tier: Tier;\n\
         \x20 fieldNumber: number;\n\
         \x20 /** Aggregation strategies the registry computes for this metric. */\n\
         \x20 aggregates: string[];\n\
         \x20 /** JSON keys the frozen legacy REST surface uses. */\n\
         \x20 legacyRestKeys: string[];\n\
         }\n\n\
         export const METRICS: readonly MetricMeta[] = [\n",
    );
    for m in reg.live_metrics() {
        let aggs: Vec<String> = m
            .aggregates
            .iter()
            .map(|a| format!("'{}'", a.name()))
            .collect();
        let keys: Vec<String> = m
            .legacy_rest_keys
            .iter()
            .map(|k| format!("'{k}'"))
            .collect();
        let _ = writeln!(
            s,
            "  {{ key: '{}', column: '{}', label: '{}', unit: '{}', tier: '{}', \
             fieldNumber: {}, aggregates: [{}], legacyRestKeys: [{}] }},",
            m.key,
            m.column,
            m.label.replace('\'', "\\'"),
            m.unit,
            match m.tier {
                Tier::Core => "core",
                Tier::Extended => "extended",
            },
            m.field_number,
            aggs.join(", "),
            keys.join(", ")
        );
    }
    s.push_str(
        "];\n\nexport const METRICS_BY_KEY: Record<string, MetricMeta> =\n  \
                Object.fromEntries(METRICS.map((m) => [m.key, m]));\n",
    );
    s
}

