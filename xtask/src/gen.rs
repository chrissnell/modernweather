// The emitters. One registry in, seven representations out.
//
// Every file carries a do-not-edit header naming the registry and the generator
// (R-2), and every file lands under `generated/` so that the drift check is one path
// and a PR touching generated code without touching the registry is wrong on sight.

use crate::registry::{Registry, Role, Tier};
use std::collections::BTreeMap;
use std::fmt::Write as _;

pub const RAW_TABLE: &str = "observations";

/// path -> contents. Written atomically by the caller, or compared by `--check`.
pub type Files = BTreeMap<String, String>;

fn header(comment: &str) -> String {
    let l = comment;
    format!(
        "{l} GENERATED by `cargo xtask codegen` from metrics/registry.toml. DO NOT EDIT.\n\
         {l}\n\
         {l} Edit metrics/registry.toml and re-run `cargo xtask codegen`. CI runs\n\
         {l} `cargo xtask codegen --check`, which regenerates into a temporary directory\n\
         {l} and diffs, so a hand edit here fails the build rather than surviving.\n\
         {l}\n\
         {l} Generator: xtask (ModernWeather). Registry: metrics/registry.toml.\n\
         {l} Snapshot:  metrics/snapshot.toml — the record of allocated identifiers.\n\n"
    )
}

pub fn all(reg: &Registry) -> Files {
    let mut f = Files::new();
    f.insert("generated/sql/010_functions.sql".into(), functions_sql());
    f.insert(format!("generated/sql/020_{RAW_TABLE}.sql"), table_sql(reg));
    for (i, lvl) in reg.levels.iter().enumerate() {
        let n = 30 + i * 10;
        f.insert(
            format!("generated/sql/{n:03}_{RAW_TABLE}_{}.sql", lvl.name),
            aggregate_sql(reg, &lvl.name),
        );
    }
    f.insert(
        "generated/sql/090_rebuild_aggregates.sql".into(),
        rebuild_sql(reg),
    );
    f.insert("generated/proto/reading.proto".into(), proto(reg));
    f.insert("generated/rust/reading.rs".into(), rust_reading(reg));
    f.insert("generated/rust/metrics.rs".into(), rust_metrics(reg));
    f.insert("generated/rust/aggregates.rs".into(), rust_aggregates(reg));
    f.insert("generated/openapi/reading.json".into(), openapi(reg));
    f.insert("generated/ts/reading.ts".into(), ts_reading(reg));
    f.insert("generated/ts/metrics.ts".into(), ts_metrics(reg));
    f
}

