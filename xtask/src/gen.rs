fn rust_reading(reg: &Registry) -> String {
    let mut s = header("//");
    s.push_str(
        "// The reading type, replacing the Go implementation's 215-field hand-maintained\n\
         // struct and the 591 lines of mapping code that existed only because the same\n\
         // metric was declared twice in incompatible shapes.\n\
         //\n\
         // Every metric field is an `Option`, because every metric column is nullable and\n\
         // \"the sensor did not report\" is not the same fact as \"the sensor reported zero\".\n\n\
         #![allow(clippy::struct_excessive_bools)]\n\n\
         use chrono::{DateTime, Utc};\n\n\
         use super::metrics::MetricKey;\n\n\
         #[derive(Debug, Clone, PartialEq, Default)]\n\
         pub struct Reading {\n",
    );
    for d in &reg.dimensions {
        let ty = d.sql_type.rust();
        let _ = writeln!(s, "    /// {} (`{}`)", d.label, d.column);
        if d.role == Role::Attribute {
            let _ = writeln!(s, "    pub {}: Option<{ty}>,", rust_ident(&d.key));
        } else {
            let _ = writeln!(s, "    pub {}: {ty},", rust_ident(&d.key));
        }
    }
    s.push('\n');
    for m in reg.live_metrics() {
        let _ = writeln!(s, "    /// {} — {} (`{}`)", m.label, m.unit, m.column);
        let _ = writeln!(
            s,
            "    pub {}: Option<{}>,",
            rust_ident(&m.key),
            m.sql_type.rust()
        );
    }
    s.push_str("}\n\nimpl Reading {\n");
    s.push_str(
        "    /// Read one metric as `f64`, for the paths that iterate rather than name a\n\
         \x20   /// field — uploaders, the management UI's metric browser, the APRS packet\n\
         \x20   /// builder. Returns `None` for an absent value and for a non-numeric metric.\n\
         \x20   #[must_use]\n\
         \x20   pub fn get(&self, key: MetricKey) -> Option<f64> {\n\
         \x20       match key {\n",
    );
    for m in reg.live_metrics() {
        let variant = pascal(&m.key);
        if m.sql_type.numeric() {
            let _ = writeln!(
                s,
                "            MetricKey::{variant} => self.{}.map(f64::from),",
                rust_ident(&m.key)
            );
        } else {
            let _ = writeln!(s, "            MetricKey::{variant} => None,");
        }
    }
    s.push_str("        }\n    }\n}\n");
    s
}

fn rust_metrics(reg: &Registry) -> String {
    let mut s = header("//");
    s.push_str(
        "// Metric metadata: the key, the column, the label the UI renders and the unit.\n\
         //\n\
         // Labels are user-facing. W5 §0 owns the internal-to-user-facing vocabulary\n\
         // translation table and is authoritative where the two disagree (D-36); these are\n\
         // written for a reader who has never seen the schema, and an internal term showing\n\
         // up on screen is a bug rather than a documentation gap.\n\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum MetricKey {\n",
    );
    for m in reg.live_metrics() {
        let _ = writeln!(s, "    {},", pascal(&m.key));
    }
    s.push_str("}\n\n");
    s.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub enum Tier {\n    Core,\n    Extended,\n}\n\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct MetricMeta {\n\
         \x20   pub key: MetricKey,\n\
         \x20   /// The registry's stable key, as it appears in metrics/registry.toml.\n\
         \x20   pub name: &'static str,\n\
         \x20   pub column: &'static str,\n\
         \x20   pub label: &'static str,\n\
         \x20   pub unit: &'static str,\n\
         \x20   pub tier: Tier,\n\
         \x20   pub field_number: u32,\n\
         \x20   /// JSON keys the frozen legacy REST surface uses for this metric. Plural\n\
         \x20   /// because the shipped surface duplicates two of them.\n\
         \x20   pub legacy_rest_keys: &'static [&'static str],\n\
         }\n\n",
    );
    let _ = writeln!(
        s,
        "pub static METRICS: [MetricMeta; {}] = [",
        reg.live_metrics().len()
    );
    for m in reg.live_metrics() {
        let keys: Vec<String> = m
            .legacy_rest_keys
            .iter()
            .map(|k| format!("\"{k}\""))
            .collect();
        let _ = writeln!(
            s,
            "    MetricMeta {{ key: MetricKey::{}, name: \"{}\", column: \"{}\", \
             label: \"{}\", unit: \"{}\", tier: Tier::{}, field_number: {}, \
             legacy_rest_keys: &[{}] }},",
            pascal(&m.key),
            m.key,
            m.column,
            m.label.replace('"', "\\\""),
            m.unit,
            match m.tier {
                Tier::Core => "Core",
                Tier::Extended => "Extended",
            },
            m.field_number,
            keys.join(", ")
        );
    }
    s.push_str("];\n");
    s
}

/// The aggregate columns, by level. W3's query layer and W5's charts both need to
/// know what an aggregate level actually holds, and neither should re-derive it.
fn rust_aggregates(reg: &Registry) -> String {
    let mut s = header("//");
    s.push_str(
        "// What each aggregate level stores. Note what is absent: there is no column\n\
         // holding a finished average and none holding a finished angle. `Mean` is a\n\
         // `_sum`/`_count` pair (or one `_stats`), `CircularMean` is a sine sum, a cosine\n\
         // sum and a count, and both are finalised at query time by mw_mean() and\n\
         // mw_circular_mean() (D-12, D-13).\n\n\
         use super::metrics::MetricKey;\n\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub enum Strategy {\n\
         \x20   Mean,\n\
         \x20   Min,\n\
         \x20   Max,\n\
         \x20   Total,\n\
         \x20   CircularMean,\n\
         }\n\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct AggregateColumn {\n\
         \x20   pub metric: MetricKey,\n\
         \x20   pub column: &'static str,\n\
         \x20   pub sql_type: &'static str,\n\
         \x20   pub strategy: Strategy,\n\
         }\n\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct Level {\n\
         \x20   pub name: &'static str,\n\
         \x20   pub view: &'static str,\n\
         \x20   pub bucket: &'static str,\n\
         \x20   /// The relation this level reads. Each level reads the level below it\n\
         \x20   /// (D-11); only the first reads the raw hypertable.\n\
         \x20   pub source: &'static str,\n\
         \x20   pub columns: &'static [AggregateColumn],\n\
         }\n\n",
    );
    for lvl in &reg.levels {
        let cols = reg.level_columns(&lvl.name);
        let _ = writeln!(
            s,
            "static LEVEL_{}_COLUMNS: [AggregateColumn; {}] = [",
            lvl.name.to_uppercase(),
            cols.len()
        );
        for (m, c) in &cols {
            let _ = writeln!(
                s,
                "    AggregateColumn {{ metric: MetricKey::{}, column: \"{}\", \
                 sql_type: \"{}\", strategy: Strategy::{:?} }},",
                pascal(&m.key),
                c.name,
                c.sql_type,
                c.strategy
            );
        }
        s.push_str("];\n\n");
    }
    let _ = writeln!(s, "pub static LEVELS: [Level; {}] = [", reg.levels.len());
    for lvl in &reg.levels {
        let source = if lvl.source == "raw" {
            RAW_TABLE.to_string()
        } else {
            format!("{RAW_TABLE}_{}", lvl.source)
        };
        let _ = writeln!(
            s,
            "    Level {{ name: \"{}\", view: \"{RAW_TABLE}_{}\", bucket: \"{}\", \
             source: \"{source}\", columns: &LEVEL_{}_COLUMNS }},",
            lvl.name,
            lvl.name,
            lvl.bucket,
            lvl.name.to_uppercase()
        );
    }
    s.push_str("];\n");
    s
}

fn rust_ident(key: &str) -> String {
    const KEYWORDS: [&str; 4] = ["type", "match", "move", "ref"];
    if KEYWORDS.contains(&key) {
        format!("r#{key}")
    } else {
        key.to_string()
    }
}

fn pascal(key: &str) -> String {
    key.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

