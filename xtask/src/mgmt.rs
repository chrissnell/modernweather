// `cargo xtask mgmt-schema [--check]` — the `mgmt-schema-drift` gate's command.
//
// Two files out of one input, and the input is the Rust handler set:
//
//   crates/mw-api-mgmt ──▶ utoipa ──▶ generated/openapi/management.json
//                                            │
//                                            └──▶ generated/ts/mgmt-api.d.ts
//
// # Why this is a gate of its own and not `codegen-drift`
//
// W5 assumption 36 expected both files to ride the existing drift gate; W9 Decision 20 had
// already settled the opposite principle for the same situation, and DESIGN.md D-57 records
// it: `cargo xtask codegen --check` should keep meaning precisely "generated/ matches
// metrics/registry.toml", because that is the sentence a reviewer relies on when a PR
// touches generated code. This emitter has a different input, so it gets its own gate --
// following `legacy-import-drift`'s precedent exactly.
//
// # Why the schema is produced by linking mw-api-mgmt rather than by reading its source
//
// `utoipa` is a set of derive macros: the schema exists only as the output of compiling the
// handlers. So `xtask` depends on `mw-api-mgmt` and calls `mw_api_mgmt::openapi_json()`,
// which means the bytes this writes were produced by the same compilation as the routes they
// describe. `xtask` is `exempt_members` in ci/layers.toml, so the dependency is outside the
// layer order by declaration rather than by accident.
//
// # Why the TypeScript is emitted here rather than by `openapi-typescript`
//
// W5 §4.2 names `openapi-typescript` for this file. It is emitted from Rust instead, and the
// reason is the gate: `mgmt-schema-drift` has to be runnable by `cargo xtask` on a machine
// with a Rust toolchain and nothing else, and a gate that needs `npm` is a gate that gets
// skipped (W8's rule that every gate is also a developer command). What §4.2 actually
// requires of this file is that it is **types only** -- no runtime, no class per endpoint, so
// that the whole client costs about 2 KB against §6.5's budget -- and a `.d.ts` is types only
// whoever writes it. The shape below is `openapi-typescript`'s, so `openapi-fetch` consumes
// it unchanged and §4.3's mechanism 2 (`tsc --noEmit` against the committed `.d.ts`) works as
// specified.

use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// The files this emitter owns, by repository-relative path.
///
/// Named as a constant because `codegen` has to know them: it prunes everything under
/// `generated/` that its own emitters do not write, so without this list `cargo xtask
/// codegen` would delete the management schema and `codegen --check` would report it as an
/// orphan.
pub const OWNED: &[&str] = &[
    "generated/openapi/management.json",
    "generated/ts/mgmt-api.d.ts",
];

/// path -> contents.
pub type Files = BTreeMap<String, String>;

/// Both files, from the handler set.
pub fn files() -> Result<Files, String> {
    let json = mw_api_mgmt::openapi_json()
        .map_err(|e| format!("the management schema could not be serialised: {e}"))?;
    let doc: Value = serde_json::from_str(&json)
        .map_err(|e| format!("the management schema is not readable back as JSON: {e}"))?;
    let mut f = Files::new();
    f.insert(OWNED[1].to_string(), typescript(&doc)?);
    f.insert(OWNED[0].to_string(), json);
    Ok(f)
}

/// The do-not-edit header `ci/layers.toml`'s `[generated]` check requires.
///
/// The JSON half cannot carry a comment, which is why that check matches the header anywhere
/// in the file rather than in its first lines: the schema's notice lives in
/// `info.description`, written by the `#[openapi(info(...))]` attribute in
/// `crates/mw-api-mgmt/src/routes.rs`.
fn header() -> String {
    "// GENERATED by `cargo xtask mgmt-schema` from the Rust handlers in\n\
     // crates/mw-api-mgmt. DO NOT EDIT.\n\
     //\n\
     // Edit the handlers and re-run `cargo xtask mgmt-schema`. CI runs\n\
     // `cargo xtask mgmt-schema --check`, which regenerates into a temporary directory\n\
     // and diffs, so a hand edit here fails the build rather than surviving.\n\
     //\n\
     // Types only: no runtime, no class per endpoint (W5 §4.2). Pair it with\n\
     // `openapi-fetch`, which is parameterised by the `paths` union below -- so\n\
     // `api.GET('/api/v1/runtime/componnts')` is a type error rather than a 404 at 2 a.m.\n\n"
        .to_string()
}

/// The `.d.ts`, in `openapi-typescript`'s shape.
fn typescript(doc: &Value) -> Result<String, String> {
    let mut s = header();

    let schemas = doc
        .pointer("/components/schemas")
        .and_then(Value::as_object)
        .ok_or("the management schema has no components/schemas")?;

    s.push_str("export interface components {\n  schemas: {\n");
    for (name, schema) in schemas {
        if let Some(d) = description(schema) {
            s.push_str(&doc_comment(&d, 4));
        }
        let _ = writeln!(s, "    {name}: {};", ts_type(schema, 4)?);
    }
    s.push_str("  };\n}\n\n");

    let paths = doc
        .pointer("/paths")
        .and_then(Value::as_object)
        .ok_or("the management schema has no paths")?;

    s.push_str("export interface paths {\n");
    for (path, item) in paths {
        let _ = writeln!(s, "  \"{path}\": {{");
        let methods = item
            .as_object()
            .ok_or_else(|| format!("the path item for `{path}` is not an object"))?;
        for (method, op) in methods {
            // `parameters` sits beside the methods on a path item and is not one.
            if !matches!(
                method.as_str(),
                "get" | "put" | "post" | "delete" | "patch" | "head" | "options" | "trace"
            ) {
                continue;
            }
            if let Some(d) = op.get("summary").and_then(Value::as_str) {
                s.push_str(&doc_comment(d, 4));
            }
            let _ = writeln!(s, "    {method}: {{");
            s.push_str(&params(op)?);
            s.push_str(&request_body(op)?);
            s.push_str(&responses(op)?);
            s.push_str("    };\n");
        }
        s.push_str("  };\n");
    }
    s.push_str("}\n");
    Ok(s)
}

/// `parameters: { path: {...}; query: {...} }`, in the shape `openapi-fetch` reads.
///
/// The four buckets are always present, and the three this API never uses are `never` rather
/// than absent: `openapi-fetch` narrows on them, and an absent key makes a call with a stray
/// `header` argument compile.
fn params(op: &Value) -> Result<String, String> {
    let list = op.get("parameters").and_then(Value::as_array);
    let mut buckets: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    for p in list.into_iter().flatten() {
        let name = p
            .get("name")
            .and_then(Value::as_str)
            .ok_or("a parameter has no name")?;
        let location = p.get("in").and_then(Value::as_str).unwrap_or("query");
        let required = p.get("required").and_then(Value::as_bool).unwrap_or(false);
        let schema = p.get("schema").cloned().unwrap_or(Value::Null);
        let ty = if schema.is_null() {
            "string".to_string()
        } else {
            ts_type(&schema, 10)?
        };
        let opt = if required { "" } else { "?" };
        buckets
            .entry(match location {
                "path" => "path",
                "header" => "header",
                "cookie" => "cookie",
                _ => "query",
            })
            .or_default()
            .push(format!("{name}{opt}: {ty}"));
    }
    let mut s = String::from("      parameters: {\n");
    for bucket in ["query", "header", "path", "cookie"] {
        match buckets.get(bucket) {
            None => {
                let _ = writeln!(s, "        {bucket}?: never;");
            }
            Some(fields) => {
                let _ = writeln!(s, "        {bucket}: {{ {} }};", fields.join("; "));
            }
        }
    }
    s.push_str("      };\n");
    Ok(s)
}

fn request_body(op: &Value) -> Result<String, String> {
    match op.pointer("/requestBody/content/application~1json/schema") {
        None => Ok("      requestBody?: never;\n".to_string()),
        Some(schema) => Ok(format!(
            "      requestBody: {{\n        content: {{\n          \
             \"application/json\": {};\n        }};\n      }};\n",
            ts_type(schema, 10)?
        )),
    }
}

fn responses(op: &Value) -> Result<String, String> {
    let list = op
        .get("responses")
        .and_then(Value::as_object)
        .ok_or("an operation has no responses")?;
    let mut s = String::from("      responses: {\n");
    for (status, response) in list {
        match response.pointer("/content/application~1json/schema") {
            None => {
                let _ = writeln!(s, "        {status}: {{ content?: never }};");
            }
            Some(schema) => {
                let _ = writeln!(
                    s,
                    "        {status}: {{ content: {{ \"application/json\": {} }} }};",
                    ts_type(schema, 10)?
                );
            }
        }
    }
    s.push_str("      };\n");
    Ok(s)
}

fn description(schema: &Value) -> Option<String> {
    schema
        .get("description")
        .and_then(Value::as_str)
        .map(str::to_string)
}

/// A doc comment, indented, with the schema's own description as its text.
///
/// One line per source line so that a Rust doc comment's paragraph breaks survive into the
/// `.d.ts`: the generated file is what a UI developer reads on hover, and a wall of text is
/// the same information with the structure removed.
fn doc_comment(text: &str, indent: usize) -> String {
    let pad = " ".repeat(indent);
    let mut s = format!("{pad}/**\n");
    for line in text.lines() {
        if line.is_empty() {
            let _ = writeln!(s, "{pad} *");
        } else {
            let _ = writeln!(s, "{pad} * {line}");
        }
    }
    let _ = writeln!(s, "{pad} */");
    s
}

/// One JSON Schema node as a TypeScript type.
///
/// Deliberately narrow: it handles what `utoipa` emits for the types in
/// `crates/mw-api-mgmt` and **fails loudly** on anything else, rather than falling back to
/// `unknown`. A silent `unknown` is the one failure mode that would make §4.3's mechanism 2
/// useless -- the UI build would keep compiling against a type that says nothing.
fn ts_type(schema: &Value, indent: usize) -> Result<String, String> {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = reference
            .rsplit('/')
            .next()
            .ok_or_else(|| format!("`{reference}` is not a usable $ref"))?;
        return Ok(format!("components[\"schemas\"][\"{name}\"]"));
    }
    // `oneOf`/`allOf`/`anyOf`. `utoipa` emits `oneOf` for a `#[serde(tag = ...)]` enum and
    // `allOf` for a `$ref` carrying a description, so both reduce to a union or an
    // intersection with no further interpretation needed.
    for (key, joiner) in [("oneOf", " | "), ("anyOf", " | "), ("allOf", " & ")] {
        if let Some(variants) = schema.get(key).and_then(Value::as_array) {
            let parts: Result<Vec<String>, String> =
                variants.iter().map(|v| ts_type(v, indent)).collect();
            return Ok(format!("({})", parts?.join(joiner)));
        }
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        let parts: Vec<String> = values
            .iter()
            .map(|v| match v {
                Value::String(s) => format!("\"{s}\""),
                other => other.to_string(),
            })
            .collect();
        return Ok(parts.join(" | "));
    }

    let ty = schema.get("type");
    // `type` can be a string or, in OpenAPI 3.1, an array including "null".
    //
    // A bare `{"type": "null"}` is a real node and not a hole: OpenAPI 3.1 is JSON Schema,
    // and `utoipa` renders an `Option<T>` whose `T` is a `$ref` as
    // `oneOf: [{$ref}, {type: "null"}]` -- it cannot put the `null` on the `$ref` itself,
    // because a `$ref` may carry no sibling keywords.
    if ty.and_then(Value::as_str) == Some("null") {
        return Ok("null".to_string());
    }
    let (name, nullable) = match ty {
        Some(Value::String(s)) => (s.as_str(), false),
        Some(Value::Array(items)) => {
            let nullable = items.iter().any(|i| i.as_str() == Some("null"));
            let concrete = items
                .iter()
                .filter_map(Value::as_str)
                .find(|s| *s != "null")
                .ok_or("a schema's type is only `null`")?;
            (concrete, nullable)
        }
        // An object with properties and no `type` is still an object; anything else with no
        // type at all is a hole in this emitter rather than a type to guess at.
        None if schema.get("properties").is_some() => ("object", false),
        None => {
            return Err(format!(
                "this schema has no type this emitter knows: {schema}"
            ))
        }
        Some(other) => return Err(format!("`type` is not a string or an array: {other}")),
    };

    let rendered = match name {
        "string" => "string".to_string(),
        "integer" | "number" => "number".to_string(),
        "boolean" => "boolean".to_string(),
        "array" => {
            let items = schema
                .get("items")
                .ok_or("an array schema has no `items`")?;
            format!("{}[]", ts_type(items, indent)?)
        }
        "object" => object(schema, indent)?,
        other => return Err(format!("`{other}` is not a type this emitter knows")),
    };
    Ok(if nullable {
        format!("({rendered} | null)")
    } else {
        rendered
    })
}

fn object(schema: &Value, indent: usize) -> Result<String, String> {
    let Some(properties) = schema.get("properties").and_then(Value::as_object) else {
        // A free-form object. `utoipa` emits one for a map; this API has exactly one, the
        // flattened log fields, and `Record<string, string>` is what it is.
        return match schema.get("additionalProperties") {
            Some(extra) => Ok(format!("Record<string, {}>", ts_type(extra, indent)?)),
            None => Err("an object schema has neither properties nor additionalProperties".into()),
        };
    };
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let pad = " ".repeat(indent + 2);
    let close = " ".repeat(indent);
    let mut s = String::from("{\n");
    for (name, property) in properties {
        if let Some(d) = description(property) {
            s.push_str(&doc_comment(&d, indent + 2));
        }
        let opt = if required.contains(&name.as_str()) {
            ""
        } else {
            "?"
        };
        let _ = writeln!(s, "{pad}{name}{opt}: {};", ts_type(property, indent + 2)?);
    }
    let _ = write!(s, "{close}}}");
    Ok(s)
}

/// `cargo xtask mgmt-schema [--check]`.
///
/// `--check` regenerates into a temporary directory and diffs; it must never write into the
/// working tree, because a check that fixes the problem it is checking for always passes
/// (DESIGN.md **R-2**).
pub fn main(root: &Path, check: bool) -> Result<std::process::ExitCode, String> {
    let files = files()?;

    if !check {
        for (path, body) in &files {
            let full = root.join(path);
            if let Some(parent) = full.parent() {
                std::fs::create_dir_all(parent)
                    .map_err(|e| format!("{}: {e}", parent.display()))?;
            }
            std::fs::write(&full, body).map_err(|e| format!("{}: {e}", full.display()))?;
        }
        println!("mgmt-schema: wrote {} files", files.len());
        for path in files.keys() {
            println!("  {path}");
        }
        return Ok(std::process::ExitCode::SUCCESS);
    }

    let mut drift: Vec<String> = Vec::new();
    for (path, want) in &files {
        match std::fs::read_to_string(root.join(path)) {
            Err(_) => drift.push(format!("  missing from the tree: {path}")),
            Ok(have) if &have != want => {
                drift.push(format!(
                    "  differs: {path}{}",
                    first_difference(&have, want)
                ));
            }
            Ok(_) => {}
        }
    }

    if drift.is_empty() {
        println!(
            "mgmt-schema --check: {} files match the handlers",
            files.len()
        );
        return Ok(std::process::ExitCode::SUCCESS);
    }

    eprintln!(
        "mgmt-schema --check: the committed schema does not match the handlers in \
         crates/mw-api-mgmt:"
    );
    for line in &drift {
        eprintln!("{line}");
    }
    eprintln!("\nRun `cargo xtask mgmt-schema` and commit the result.");
    Ok(std::process::ExitCode::from(1))
}

/// The first line that differs, so the gate's message is actionable without a diff tool.
fn first_difference(have: &str, want: &str) -> String {
    for (i, (a, b)) in have.lines().zip(want.lines()).enumerate() {
        if a != b {
            return format!(
                "\n      line {}: committed `{}`\n      line {}: derived   `{}`",
                i + 1,
                a.trim(),
                i + 1,
                b.trim()
            );
        }
    }
    let (h, w) = (have.lines().count(), want.lines().count());
    if h == w {
        return String::new();
    }
    format!("\n      the committed file has {h} lines and the derived one has {w}")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The emitter is the gate, so the thing worth asserting is that it runs over the real
    /// handler set rather than over a fixture: a `ts_type` hole only shows up against the
    /// shapes `crates/mw-api-mgmt` actually has.
    #[test]
    fn both_files_are_emitted_from_the_real_handlers() {
        let f = files().expect("the handlers emit a schema");
        assert_eq!(f.len(), OWNED.len());
        for path in OWNED {
            assert!(f.contains_key(*path), "{path} was not emitted");
        }
    }

    /// `ci/layers.toml`'s `[generated]` check requires the do-not-edit header on everything
    /// under `generated/`. The JSON cannot carry a comment, so its notice is in
    /// `info.description` -- asserted here because the gate's own message would otherwise be
    /// the first place anyone found out.
    #[test]
    fn both_files_announce_that_they_are_generated() {
        let f = files().expect("the handlers emit a schema");
        for (path, body) in &f {
            assert!(
                body.to_uppercase().contains("DO NOT EDIT"),
                "{path} does not say it is generated"
            );
        }
    }

    /// Types only (W5 §4.2): no runtime, no class per endpoint. A `.d.ts` that declared a
    /// `const` or a `class` would contribute to the bundle rather than to the type check,
    /// which is the whole reason §4.2 chose a types-only client over a generated method per
    /// endpoint -- §6.5's budget is 150 KB for the initial route.
    ///
    /// Over the **declarations** rather than over the text: the header says the words
    /// "no class per endpoint" and a substring scan would find them there, which is a test
    /// that fails on its own explanation.
    #[test]
    fn the_typescript_declares_no_runtime() {
        let f = files().expect("the handlers emit a schema");
        let ts = &f["generated/ts/mgmt-api.d.ts"];
        for line in ts.lines() {
            let code = line.trim();
            if code.starts_with("//") || code.starts_with("*") || code.starts_with("/*") {
                continue;
            }
            for runtime in ["class ", "const ", "function ", "=>"] {
                assert!(
                    !code.contains(runtime),
                    "`{code}` is runtime rather than types"
                );
            }
        }
        assert!(ts.contains("export interface paths {"));
        assert!(ts.contains("export interface components {"));
    }

    /// Every operation reaches the `.d.ts`, because §4.3's mechanism 2 only turns a 404 into
    /// a build failure for the paths it knows: a path missing from this union is a path
    /// `openapi-fetch` cannot type-check at all.
    #[test]
    fn every_operation_reaches_the_typescript() {
        let json = mw_api_mgmt::openapi_json().expect("the schema serialises");
        let doc: serde_json::Value = serde_json::from_str(&json).expect("it reads back");
        let ts = typescript(&doc).expect("the client emits");
        let paths = doc
            .pointer("/paths")
            .and_then(Value::as_object)
            .expect("paths");
        let operations: usize = paths
            .values()
            .filter_map(Value::as_object)
            .map(|item| {
                item.keys()
                    .filter(|m| matches!(m.as_str(), "get" | "put" | "post" | "delete" | "patch"))
                    .count()
            })
            .sum();
        // A floor rather than an exact number: this asserts that the emitter saw the whole
        // handler set, and a route added later should not have to edit a test to land.
        assert!(operations >= 35, "only {operations} operations");
        for path in paths.keys() {
            assert!(ts.contains(&format!("\"{path}\":")), "{path} is missing");
            let item = paths[path].as_object().expect("a path item");
            for method in item.keys() {
                if matches!(method.as_str(), "get" | "put" | "post" | "delete") {
                    assert!(
                        ts.contains(&format!("    {method}: {{")),
                        "{path} {method} is missing"
                    );
                }
            }
        }
    }

    /// The message names the line, so a failing gate is actionable from the log alone.
    #[test]
    fn the_drift_message_names_the_first_differing_line() {
        let d = first_difference("a\nb\nc\n", "a\nX\nc\n");
        assert!(d.contains("line 2"), "{d}");
        assert!(d.contains('X'), "{d}");
        assert_eq!(first_difference("a\n", "a\n"), "");
        assert!(first_difference("a\n", "a\nb\n").contains("1 lines"));
    }
}
