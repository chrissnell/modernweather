//! The migration generator: registry diffed against the committed snapshot, emitted
//! as one timestamped `sqlx` migration.
//!
//! No DDL at startup, ever (D-8). The Go implementation's `CREATE TABLE IF NOT
//! EXISTS` startup path is why its schema has been frozen at first-run shape for 58
//! migrations and why the source definition has drifted 72 columns ahead of the
//! database it writes to.

use crate::gen;
use crate::registry::Registry;
use crate::snapshot::{self, Change, Class, Snapshot};
use std::fmt::Write as _;

pub struct Migration {
    pub filename: String,
    pub body: String,
}

pub fn render(
    reg: &Registry,
    prev: &Snapshot,
    changes: &[Change],
    bootstrap: bool,
    stamp: &str,
    name: &str,
) -> Migration {
    let mut s = String::new();

    if bootstrap {
        s.push_str(
            "-- GENERATED by `cargo xtask migrate` from metrics/registry.toml. DO NOT EDIT.\n\
             --\n\
             -- Initial schema: support functions, the raw hypertable with compression, and\n\
             -- the aggregate hierarchy. Each piece is the generator's own output; the same\n\
             -- statements exist as standalone files under generated/sql/.\n\
             --\n",
        );
        let _ = writeln!(
            s,
            "-- {} metrics and {} dimensions, bootstrapped from the Go implementation's own\n\
             -- 215-column definition. Production carries ~143 columns; the gap is a defect in\n\
             -- the old system and W9 reconciles it (OQ-6).\n",
            reg.metrics.len(),
            reg.stored_dimensions().len()
        );
        for (path, body) in gen::all(reg) {
            if !path.starts_with("generated/sql/") || path.ends_with("090_rebuild_aggregates.sql") {
                continue;
            }
            let _ = writeln!(s, "-- ===== {path} =====\n");
            s.push_str(strip_header(&body));
            s.push('\n');
        }
        s.push_str(
            "-- The aggregates are created WITH NO DATA. Materialising them is\n\
             -- generated/sql/090_rebuild_aggregates.sql, which must run outside a\n\
             -- transaction and with relaxed commit durability (D-17).\n",
        );
        return Migration {
            filename: format!("{stamp}_{name}.sql"),
            body: s,
        };
    }

    s.push_str(
        "-- GENERATED by `cargo xtask migrate` from metrics/registry.toml. DO NOT EDIT.\n\
         --\n\
         -- Review it before you run it, then commit it as it stands. Hand-editing a\n\
         -- migration decouples the database from metrics/snapshot.toml, which is the only\n\
         -- record of what has been allocated.\n--\n",
    );

    // ---- classified summary, in the migration itself -----------------------
    s.push_str("-- Classified changes:\n");
    for c in changes {
        let _ = writeln!(
            s,
            "--   [{}] {}: {}",
            crate::validate::class_label(c.class),
            c.key,
            c.detail
        );
    }
    s.push_str("--\n");

    let breaking: Vec<&Change> = changes.iter().filter(|c| c.class.breaking()).collect();
    if !breaking.is_empty() {
        s.push_str(
            "-- !! THIS MIGRATION WAS GENERATED WITH --allow-breaking. It contains statements\n\
             -- !! that destroy data or break a shipped contract. Every one of them is listed\n\
             -- !! above with class BREAKING. Read them before running this.\n--\n",
        );
    }

    // The finalisers, in every migration. They are the one piece of generated SQL whose
    // *body* can change without any identifier changing — W4 made mw_circular_mean return
    // 0 rather than NULL for an empty bucket (OQ-W1-2 option (c)) — and before this they
    // were emitted only by the bootstrap migration, so such a change reached generated/
    // and never reached a deployed database. They are CREATE OR REPLACE and no continuous
    // aggregate inlines them, so re-asserting them is idempotent and cheap.
    s.push_str("-- Finalisers, re-asserted. See generated/sql/010_functions.sql.\n\n");
    s.push_str(strip_header(&gen::finalisers()));
    s.push('\n');

    let adds: Vec<&Change> = changes
        .iter()
        .filter(|c| c.class == Class::AddColumn)
        .collect();

    // Guarded on the columns, not on the change count: a new `metadata` dimension is
    // classified AddColumn so that the snapshot records its protobuf field number, and
    // it adds no column at all. Keying the block on `adds` emitted `ALTER TABLE
    // observations ;` for it.
    let add_cols: Vec<String> = adds
        .iter()
        .filter_map(|c| added_column(reg, &c.key))
        .collect();

    if !add_cols.is_empty() {
        s.push_str(
            "-- Adding nullable columns. Measured at 11.6 ms against ~1 GB of compressed\n\
             -- chunks, 93 ms for twenty columns in one statement, and nothing decompressed\n\
             -- (D-9).\n\
             --\n\
             -- The caveat is the lock, not the work: the statement takes AccessExclusiveLock\n\
             -- on the hypertable, every chunk and every compressed mirror — 63 relations on\n\
             -- the spike instance — for the ~12 ms it runs. It is instant but it queues\n\
             -- behind long-running readers and blocks everything while it waits. So it fails\n\
             -- fast and retries rather than stalling the API.\n\n\
             SET LOCAL lock_timeout = '3s';\n\n\
             DO $migration$\n\
             DECLARE\n\
             \x20   attempt int := 0;\n\
             BEGIN\n\
             \x20   LOOP\n\
             \x20       BEGIN\n",
        );
        let _ = writeln!(
            s,
            "            ALTER TABLE {}\n                {};",
            gen::RAW_TABLE,
            add_cols.join(",\n                ")
        );
        s.push_str(
            "            EXIT;\n\
             \x20       EXCEPTION WHEN lock_not_available THEN\n\
             \x20           attempt := attempt + 1;\n\
             \x20           IF attempt >= 10 THEN\n\
             \x20               RAISE;\n\
             \x20           END IF;\n\
             \x20           RAISE NOTICE 'lock_timeout on attempt %, retrying', attempt;\n\
             \x20           PERFORM pg_sleep(attempt);\n\
             \x20       END;\n\
             \x20   END LOOP;\n\
             END $migration$;\n\n",
        );
    }

    for c in &breaking {
        if let Some((old, new)) = parse_rename(&c.detail) {
            let _ = writeln!(
                s,
                "-- BREAKING: renaming a column. The attribute number stays where it is and\n\
                 -- the old name is never reusable again. Every generated artefact changes\n\
                 -- with it, and any external consumer reading the old name breaks.\n\
                 ALTER TABLE {} RENAME COLUMN {old} TO {new};\n",
                gen::RAW_TABLE
            );
        }
        if let Some(col) = c
            .detail
            .strip_prefix("role changed to \"metadata\": column ")
        {
            let col = col.split_whitespace().next().unwrap_or(col);
            let _ = writeln!(
                s,
                "-- BREAKING: {col} is no longer a generated column. There is deliberately no\n\
                 -- DROP COLUMN here: a dropped column keeps its attribute number forever and\n\
                 -- is charged twice against the 1600-column ceiling once the hypertable is\n\
                 -- compressed (H-4, D-19). The column stays where it is, unwritten, and\n\
                 -- metrics/snapshot.toml keeps the identifier allocated. Stop writing it\n\
                 -- before you run this, or readings lose the value with no error.\n\
                 -- Drop it by hand, later, if a full table rewrite is ever worth the\n\
                 -- reclaimed slot."
            );
        }
        if let Some((col, from, to)) = parse_type_change(reg, c) {
            let _ = writeln!(
                s,
                "-- BREAKING: changing {col} from {from} to {to} rewrites the column. On a\n\
                 -- compressed hypertable this requires decompressing every chunk that holds\n\
                 -- it and recompressing afterwards; budget for it, and do not run it against\n\
                 -- a live API.\n\
                 ALTER TABLE {} ALTER COLUMN {col} TYPE {to};\n",
                gen::RAW_TABLE
            );
        }
    }

    // Which levels this migration drops and recreates. Compared against the snapshot's
    // own record of each level's definition (N-13), so a change that leaves a level's
    // text alone leaves the level alone.
    let levels = snapshot::affected_levels(reg, prev);
    // Levels the registry no longer declares. Dropped and not recreated, so they are a
    // separate list from the rebuild set above — and before the snapshot recorded levels
    // there was no way to compute this one, which is why removing a `[[level]]` used to
    // leave its continuous aggregate and both its policies in the database forever.
    let gone = snapshot::removed_levels(reg, prev);
    if !gone.is_empty() {
        s.push_str(
            "-- Levels the registry no longer declares. These are dropped and NOT recreated.\n             -- Top-down, because a level that is still declared may read one of them.\n             -- CASCADE takes the refresh and retention policies with the view, which is\n             -- correct here: the level is gone, so its policies have nothing to act on.\n\n",
        );
        for name in gone.iter().rev() {
            let _ = writeln!(
                s,
                "DROP MATERIALIZED VIEW IF EXISTS {}_{name} CASCADE;",
                gen::RAW_TABLE
            );
        }
        s.push('\n');
    }
    if !levels.is_empty() {
        s.push_str(
            "-- Aggregates are disposable derived data (D-15): there is no in-place aggregate\n\
             -- migration. The supported change is drop, regenerate, refresh. Dropping is\n\
             -- top-down because each level reads the level below it.\n\n",
        );
        for lvl in reg.levels.iter().rev() {
            if levels.contains(&lvl.name) {
                let _ = writeln!(
                    s,
                    "DROP MATERIALIZED VIEW IF EXISTS {}_{} CASCADE;",
                    gen::RAW_TABLE,
                    lvl.name
                );
            }
        }
        s.push('\n');
        for lvl in &reg.levels {
            if levels.contains(&lvl.name) {
                s.push_str(strip_header(&gen::aggregate_definition(reg, &lvl.name)));
                s.push('\n');
            }
        }
        s.push_str(
            "-- Recreated WITH NO DATA. Materialising them is\n\
             -- generated/sql/090_rebuild_aggregates.sql, which cannot run inside a\n\
             -- transaction and must relax commit durability (D-17): 306 s against 25.6 s on\n\
             -- the measured rebuild. W4 owns the procedure; this migration only produces the\n\
             -- shape it executes.\n",
        );
    }

    if add_cols.is_empty() && levels.is_empty() && gone.is_empty() && breaking.is_empty() {
        s.push_str(
            "-- Beyond the finalisers above there is nothing to do: the registry changed only\n\
             -- in things the database does not hold (labels, units, tiers, legacy key\n\
             -- mappings, and the protobuf-only `metadata` dimensions of N-14). Regenerate\n\
             -- and commit generated/ instead.\n",
        );
    }

    Migration {
        filename: format!("{stamp}_{name}.sql"),
        body: s,
    }
}

/// The `ALTER TABLE` clause an `AddColumn` change needs, or `None` when the change adds
/// no column.
///
/// Exhaustive by construction: `snapshot::from_registry` emits one entry per metric and
/// one per dimension, so an `AddColumn` key is always one or the other, and the only
/// entry that adds no column is a `metadata` dimension (N-14). Resolving dimensions here
/// is not hypothetical tidiness — searching only `reg.metrics` meant a new `[[dimension]]`
/// reached `generated/sql/` through `codegen` and never reached a deployed database
/// through `migrate`, while the migration's own header classified it "add nullable
/// column". That is D-8's drift, generated by the tool meant to prevent it.
///
/// `NULL` rather than `NOT NULL` is correct for every dimension that can arrive this way:
/// a populated table rejects a NOT NULL column without a default, and the two NOT NULL
/// roles cannot be added post-bootstrap anyway — `registry_internal` requires exactly one
/// `time` and exactly one `partition` dimension, so both already exist.
fn added_column(reg: &Registry, key: &str) -> Option<String> {
    let clause = |col: &str, ty: &str| format!("ADD COLUMN {col} {ty} NULL");
    if let Some(m) = reg.metrics.iter().find(|m| m.key == key) {
        return Some(clause(&m.column, m.sql_type.ddl()));
    }
    let d = reg.dimensions.iter().find(|d| d.key == key)?;
    d.role.stored().then(|| clause(&d.column, d.sql_type.ddl()))
}

/// Generated SQL files carry a do-not-edit header aimed at someone reading the file
/// standalone. Inside a migration it is noise, and the migration has its own.
fn strip_header(body: &str) -> &str {
    let mut rest = body;
    while let Some(nl) = rest.find('\n') {
        let line = &rest[..nl];
        if line.starts_with("--") || line.trim().is_empty() {
            rest = &rest[nl + 1..];
        } else {
            break;
        }
    }
    // Keep the explanatory comment block that follows the header, which starts at the
    // first line that is not part of the generator banner. The loop above also eats
    // that block, so instead find the banner's end explicitly.
    match body.find("-- Snapshot:") {
        Some(i) => match body[i..].find("\n\n") {
            Some(j) => &body[i + j + 2..],
            None => body,
        },
        None => body,
    }
}

fn parse_rename(detail: &str) -> Option<(String, String)> {
    let rest = detail.strip_prefix("column renamed ")?;
    let (a, b) = rest.split_once(" -> ")?;
    Some((a.to_string(), b.to_string()))
}

fn parse_type_change(reg: &Registry, c: &Change) -> Option<(String, String, String)> {
    let rest = c.detail.strip_prefix("SQL type changed ")?;
    let (from, to) = rest.split_once(" -> ")?;
    let col = reg
        .metrics
        .iter()
        .find(|m| m.key == c.key)
        .map(|m| m.column.clone())
        .or_else(|| {
            reg.dimensions
                .iter()
                .find(|d| d.key == c.key)
                .map(|d| d.column.clone())
        })?;
    Some((col, from.to_string(), to.to_string()))
}

/// `YYYYMMDDHHMMSS`, the shape `sqlx migrate` orders by.
pub fn stamp(secs: u64) -> String {
    let days = (secs / 86_400) as i64;
    let rem = secs % 86_400;
    let (y, m, d) = civil_from_days(days);
    format!(
        "{y:04}{m:02}{d:02}{:02}{:02}{:02}",
        rem / 3600,
        (rem % 3600) / 60,
        rem % 60
    )
}

/// Howard Hinnant's `civil_from_days`. Avoids a date dependency for the one thing a
/// date dependency would be used for.
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

#[cfg(test)]
mod tests {
    use super::stamp;

    #[test]
    fn stamps_are_sqlx_ordered() {
        assert_eq!(stamp(0), "19700101000000");
        assert_eq!(stamp(1_761_609_600), "20251028000000");
        assert_eq!(stamp(1_793_205_045), "20261028163045");
        // A leap day, because this is hand-rolled calendar arithmetic.
        assert_eq!(stamp(1_709_208_000), "20240229120000");
        assert!(stamp(1_761_609_600) < stamp(1_761_696_000));
    }
}
